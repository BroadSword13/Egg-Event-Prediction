'use strict';
const test = require('node:test'), assert = require('node:assert/strict');
for (const f of ['config','utils','clock']) require('../src/'+f+'.js');
require('../data/seed-events.js');
for (const f of ['store','model','accuracy']) require('../src/'+f+'.js');
const a = globalThis.EggEventLab;
let day = '2026-09-23';
a.clock.currentEventDate = () => day;
a.clock.now = () => new Date(day+'T20:00:00Z');
const probabilities = Object.fromEntries(a.config.MODEL_ORDER.map(id=>[id,0]));
probabilities.drone_green=0.8; probabilities.housing_blue=0.2;
probabilities.drone_pink=0.3; probabilities.housing_pink=0.7;
test('archive persists, freezes after release, and only scores confirmed outcomes', () => {
  a.accuracy.save('2026-09-24', probabilities);
  assert.equal(a.store.getState().predictionArchive['2026-09-24'].probabilities.drone_green,0.8);
  day='2026-09-24';
  a.accuracy.save(day,{...probabilities,drone_green:0});
  assert.equal(a.store.getState().predictionArchive[day].probabilities.drone_green,0.8);
  assert.equal(a.accuracy.summarize().overall.count,0);
  a.store.getState().overrides[day]=['drone_green','housing_pink'];
  const s=a.accuracy.summarize();
  assert.equal(s.overall.count,2);
  assert.ok(Math.abs(s.nonUltra.score-96)<1e-9);
  assert.ok(Math.abs(s.ultra.score-91)<1e-9);
  assert.ok(Math.abs(s.overall.score-93.5)<1e-9);
  assert.equal(s.overall.top,1);
  const copy=JSON.parse(JSON.stringify(a.store.getState().predictionArchive));
  assert.deepEqual(a.accuracy.normalize(copy),copy);
  copy[day].savedAt='2026-09-24T20:00:00Z';
  assert.deepEqual(a.accuracy.normalize(copy),{});
  day='2026-10-24';
  assert.equal(a.accuracy.summarize(30).overall.count,0);
  assert.equal(a.accuracy.summarize(90).overall.count,2);
});
